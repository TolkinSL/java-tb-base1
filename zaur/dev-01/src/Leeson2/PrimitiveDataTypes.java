package Leeson2;

public class PrimitiveDataTypes {
    public static void main(String[] args) {
        {
            byte b1 = 10;
            System.out.println(b1);

            long l1 = 121;
            long l2 = 10000000000L;

            float f1 = 3.14f;

            double d2 = 3.14;
            double d3 = 2323.232;
            double d4 = 232.23D;

            char c1 = 'a';
            char c2 = 'A';
            char c3 = '7';
            char c4 = ' ';
            char c5 = '\u1323';

            System.out.println(c5);

            boolean bl1 = true;
            System.out.println(bl1);

            int a1 = 60;
            int a2 = 0B111100;
            int a3 = 0747;
            int a4 = 0x3c;
        }
    }
}
